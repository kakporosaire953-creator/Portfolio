/**
 * Noise used by the sculptures.
 *
 * Two faces of the same idea:
 * - `valueNoise2` runs on the CPU, once, while the geometry is built. It gives
 *   the ghost its hand-shaped irregularity and makes the build deterministic
 *   (no `Math.random`, so a reload always yields the same sculpture).
 * - `SNOISE_GLSL` runs on the GPU, every frame, for the slow breathing
 *   displacement. Doing that on the CPU would mean re-uploading ~60k vertices
 *   per frame; the shader costs a few million instructions instead of a
 *   megabyte of bus traffic.
 */

/** 2D value noise, smooth, periodic-free, deterministic. */
export function valueNoise2(x: number, y: number): number {
  const xi = Math.floor(x);
  const yi = Math.floor(y);
  const xf = x - xi;
  const yf = y - yi;

  const u = xf * xf * (3 - 2 * xf);
  const v = yf * yf * (3 - 2 * yf);

  const a = hash2(xi, yi);
  const b = hash2(xi + 1, yi);
  const c = hash2(xi, yi + 1);
  const d = hash2(xi + 1, yi + 1);

  const top = a + (b - a) * u;
  const bottom = c + (d - c) * u;
  return (top + (bottom - top) * v) * 2 - 1; // -1 … 1
}

function hash2(x: number, y: number): number {
  let h = x * 374761393 + y * 668265263;
  h = (h ^ (h >>> 13)) * 1274126177;
  h = h ^ (h >>> 16);
  return (h >>> 0) / 4294967295;
}

/** Two octaves, which is all a hand-shaped veil needs. */
export function fbm2(x: number, y: number): number {
  return valueNoise2(x, y) * 0.68 + valueNoise2(x * 2.17 + 11.3, y * 2.17 - 7.1) * 0.32;
}

/** Smooth 0 → 1 ramp. */
export function smoothstep(edge0: number, edge1: number, x: number): number {
  const t = Math.min(1, Math.max(0, (x - edge0) / (edge1 - edge0)));
  return t * t * (3 - 2 * t);
}

/**
 * Simplex noise (Ashima Arts / Stefan Gustavson, MIT) under a `noiseK` prefix so
 * it cannot collide with three.js internals.
 */
export const SNOISE_GLSL = /* glsl */ `
vec3 mod289K(vec3 x) { return x - floor(x * (1.0 / 289.0)) * 289.0; }
vec4 mod289K(vec4 x) { return x - floor(x * (1.0 / 289.0)) * 289.0; }
vec4 permuteK(vec4 x) { return mod289K(((x * 34.0) + 1.0) * x); }
vec4 taylorInvSqrtK(vec4 r) { return 1.79284291400159 - 0.85373472095314 * r; }

float noiseK(vec3 v) {
  const vec2 C = vec2(1.0 / 6.0, 1.0 / 3.0);
  const vec4 D = vec4(0.0, 0.5, 1.0, 2.0);

  vec3 i  = floor(v + dot(v, C.yyy));
  vec3 x0 = v - i + dot(i, C.xxx);

  vec3 g = step(x0.yzx, x0.xyz);
  vec3 l = 1.0 - g;
  vec3 i1 = min(g.xyz, l.zxy);
  vec3 i2 = max(g.xyz, l.zxy);

  vec3 x1 = x0 - i1 + C.xxx;
  vec3 x2 = x0 - i2 + C.yyy;
  vec3 x3 = x0 - D.yyy;

  i = mod289K(i);

  vec4 p = permuteK(permuteK(permuteK(
            i.z + vec4(0.0, i1.z, i2.z, 1.0))
          + i.y + vec4(0.0, i1.y, i2.y, 1.0))
          + i.x + vec4(0.0, i1.x, i2.x, 1.0));

  float n_ = 0.142857142857;
  vec3 ns = n_ * D.wyz - D.xzx;

  vec4 j = p - 49.0 * floor(p * ns.z * ns.z);

  vec4 x_ = floor(j * ns.z);
  vec4 y_ = floor(j - 7.0 * x_);

  vec4 x = x_ * ns.x + ns.yyyy;
  vec4 y = y_ * ns.x + ns.yyyy;
  vec4 h = 1.0 - abs(x) - abs(y);

  vec4 b0 = vec4(x.xy, y.xy);
  vec4 b1 = vec4(x.zw, y.zw);

  vec4 s0 = floor(b0) * 2.0 + 1.0;
  vec4 s1 = floor(b1) * 2.0 + 1.0;
  vec4 sh = -step(h, vec4(0.0));

  vec4 a0 = b0.xzyw + s0.xzyw * sh.xxyy;
  vec4 a1 = b1.xzyw + s1.xzyw * sh.zzww;

  vec3 p0 = vec3(a0.xy, h.x);
  vec3 p1 = vec3(a0.zw, h.y);
  vec3 p2 = vec3(a1.xy, h.z);
  vec3 p3 = vec3(a1.zw, h.w);

  vec4 norm = taylorInvSqrtK(vec4(dot(p0, p0), dot(p1, p1), dot(p2, p2), dot(p3, p3)));
  p0 *= norm.x;
  p1 *= norm.y;
  p2 *= norm.z;
  p3 *= norm.w;

  vec4 m = max(0.6 - vec4(dot(x0, x0), dot(x1, x1), dot(x2, x2), dot(x3, x3)), 0.0);
  m = m * m;
  return 42.0 * dot(m * m, vec4(dot(p0, x0), dot(p1, x1), dot(p2, x2), dot(p3, x3)));
}
`;
